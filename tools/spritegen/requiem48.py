"""Source of truth for the Requiem 48 palette (docs/sprite-pipeline.md §2.1).
The 16 approved Requiem 16 colours are kept exactly and marked '*'."""
from __future__ import annotations

from pathlib import Path

RAMPS: list[tuple[str, list[str]]] = [
    ("near-blacks / outline", ["0b0a10*", "14111c", "1c1826*", "251f30"]),
    ("stone greys", ["2e2836*", "3b3444", "4a4252*", "5c5464", "6f6676*", "8a8392"]),
    ("bone / marble whites", ["a59fb0", "b8b1c4", "c9c2d6*", "ddd7e6", "efeaf2*"]),
    ("coat black-violets", ["180f20", "241b2e*", "32263e", "41324f"]),
    ("blood crimsons", ["2e0811", "4a0f1b*", "6a1524", "8e1b2c*", "ad2a3a"]),
    ("crusnik reds", ["d4283e*", "e85a5f", "f39a8f"]),
    ("candle ambers / browns", ["3d2512", "5a3618", "7a4a1e*", "a86b2a", "d9963a*"]),
    ("vatican golds", ["9c7a2c", "c4a04a", "e8c86a*", "f6e3a3"]),
    ("crusnik / tech pale blues", ["2f4a63", "4f7c9e", "7fb6d6*", "bfe0ef"]),
    ("decay greens", ["34503a", "5f8a5a*", "8fb27f"]),
    ("flesh", ["8a5a4c", "b8826b", "dcb39a"]),
    ("reserved FX: hit flash, stun signal", ["ffffff", "ffe14d"]),
]


def colours() -> list[str]:
    return [c.rstrip("*") for _, ramp in RAMPS for c in ramp]


def anchors() -> list[str]:
    return [c.rstrip("*") for _, ramp in RAMPS for c in ramp if c.endswith("*")]


def write(out_dir: Path) -> tuple[Path, Path]:
    """Writes requiem48.hex (commented by ramp), requiem16.hex and a 48x1 swatch PNG."""
    from PIL import Image

    out_dir.mkdir(parents=True, exist_ok=True)
    lines = ["; Requiem 48 - generated by tools/spritegen/requiem48.py. '*' = approved Requiem 16 anchor."]
    for name, ramp in RAMPS:
        lines.append(f"; {name}")
        lines += [f"{c.rstrip('*')}{' ; *' if c.endswith('*') else ''}" for c in ramp]
    hex48 = out_dir / "requiem48.hex"
    hex48.write_text("\n".join(lines) + "\n")
    (out_dir / "requiem16.hex").write_text("; Requiem 16 (approved creative direction)\n" + "\n".join(anchors()) + "\n")
    img = Image.new("RGB", (len(colours()), 1))
    img.putdata([tuple(int(c[i : i + 2], 16) for i in (0, 2, 4)) for c in colours()])
    png = out_dir / "requiem48.png"
    img.save(png, optimize=False)
    return hex48, png
